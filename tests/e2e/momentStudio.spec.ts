import { expect, test, type Page } from "@playwright/test";
import { mkdirSync } from "node:fs";
import { login } from "./login";
const SHOTS = "docs/ux-moments";
mkdirSync(SHOTS, { recursive: true });
async function open(page: Page) {
  await login(page);
  await page.goto("/");
  await expect(page.getByTestId("moment-text")).toBeVisible();
  await expect(page.locator(".stage-loading")).toHaveCount(0, { timeout: 90_000 });
  await expect(page.locator(".stage-error")).toHaveCount(0);
}
async function previewAndFinish(page: Page, index: number) {
  await page.getByTestId("preview-moment").click();
  await expect(page.getByTestId("moment-card").nth(index)).toHaveAttribute("data-status", "ready", { timeout: 40_000 });
  await expect.poll(() => page.evaluate(() => window.__mabear!.t())).toBeGreaterThan(0);
  await expect.poll(() => page.evaluate(() => window.__mabear!.playing()), { timeout: 40_000 }).toBe(false);
  const info = await page.evaluate((i) => {
    const tl = window.__mabear!.timeline() as { segments: { offset: number; segment: { duration: number } }[] };
    const seg = tl.segments[i];
    return { t: window.__mabear!.t(), start: seg.offset, end: seg.offset + seg.segment.duration };
  }, index);
  expect(info.t).toBeGreaterThanOrEqual(info.start);
  expect(Math.abs(info.t - info.end)).toBeLessThan(.15);
}

